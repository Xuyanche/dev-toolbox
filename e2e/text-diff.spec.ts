test('difference navigation reveals all three targets despite unequal preceding blocks', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.setViewportSize({ width: 1280, height: 768 })
  const before = Array.from({ length: 50 }, (_, i) => `before_${i}: same\n`).join('')
  const between = Array.from({ length: 5 }, (_, i) => `between_${i}: same\n`).join('')
  const after = Array.from({ length: 80 }, (_, i) => `after_${i}: same\n`).join('')
  const extra = Array.from({ length: 120 }, (_, i) => `extra_${i}: right\n`).join('')
  await compare(page, `${before}first: left\n${between}selected: left\n${after}`, `${before}${extra}${between}selected: right\n${after}`)
  const chooser = page.getByRole('combobox', { name: '当前差异' })
  async function expectTargets() {
    for (const side of ['left', 'result', 'right'] as const) {
      await expect(editor(page, side).locator('.cm-line').filter({ hasText: /^selected:/ })).toBeInViewport()
    }
  }
  await chooser.selectOption('1')
  await expectTargets()
  // A later scroll/measurement event must not pull the other targets away again.
  await page.waitForTimeout(150)
  await expectTargets()
  await page.locator('.text-pane-left .cm-scroller').evaluate(element => { element.scrollTop = 0 })
  await expect.poll(() => page.locator('.text-pane-right .cm-scroller').evaluate(element => element.scrollTop)).toBe(0)
  await page.getByRole('button', { name: '上一处差异' }).click()
  await page.getByRole('button', { name: '下一处差异' }).click()
  await expectTargets()
  await page.getByRole('checkbox', { name: '隐藏相同内容' }).check()
  await chooser.selectOption('0'); await chooser.selectOption('1')
  await expectTargets()
  expect(errors).toEqual([])
  await page.getByRole('checkbox', { name: '锁定滚动' }).uncheck()
  await chooser.selectOption('0'); await chooser.selectOption('1')
  await expectTargets()
})

