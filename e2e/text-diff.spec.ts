async function openTool(page: Page) {
  await page.goto('/')
  await selectTextTool(page)
}
async function selectTextTool(page: Page) {
  if (page.viewportSize()!.width < 761) await page.getByRole('navigation', { name: '移动工具导航' }).getByRole('button', { name: '文本对比', exact: true }).click()
  else {
    const nav = page.getByRole('navigation', { name: '工具导航', exact: true })
    const category = nav.getByRole('button', { name: '文本工具', exact: true })
    if (await category.getAttribute('aria-expanded') !== 'true') await category.click()
    await nav.getByRole('button', { name: /文本对比/ }).click()
  }
}
const textOf = async (page: Page, side: 'left' | 'result' | 'right') => (await editor(page, side).locator('.cm-line').allTextContents()).join('\n')
const editor = (page: Page, side: 'left' | 'result' | 'right') => page.getByRole('textbox', { name: side === 'left' ? '左侧 YAML' : side === 'right' ? '右侧 YAML' : '融合结果', exact: true })
async function compare(page: Page, left: string, right: string) {
  await openTool(page); await editor(page, 'left').fill(left); await editor(page, 'right').fill(right)
  await page.getByRole('button', { name: '开始比较', exact: true }).click()
  await expect(page.locator('.text-state')).toContainText(/草稿|合并完成/, { timeout: 15_000 })
}
async function sample(page: Page) {
  await openTool(page)
  await page.getByLabel('导入左侧原文文件').setInputFiles({ name: 'local.yaml', mimeType: 'text/yaml', buffer: Buffer.from(YAML_LEFT) })
  await page.getByLabel('导入右侧原文文件').setInputFiles({ name: 'deploy.yaml', mimeType: 'text/yaml', buffer: Buffer.from(YAML_RIGHT) })
  await page.getByRole('button', { name: '开始比较', exact: true }).click()
  await expect(page.getByRole('button', { name: '采用右侧', exact: true })).toBeEnabled()
}
async function downloadFile(page: Page, label: string, options: { filename?: string; eol?: 'LF' | 'CRLF' } = {}) {
  await page.getByRole('button', { name: label, exact: true }).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog).toBeVisible()
  if (options.filename) await dialog.getByLabel('结果文件名').fill(options.filename)
  if (options.eol) await dialog.getByLabel('导出换行风格').selectOption(options.eol)
  const promise = page.waitForEvent('download')
  await dialog.getByRole('button', { name: '下载文件', exact: true }).click()
  return promise
}

