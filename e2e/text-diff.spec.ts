test('locked scrolling follows both axes and short panes cannot pull a long pane back', async ({ page }) => {
  await page.setViewportSize({ width: 1920, height: 1080 })
  const left = `value: ${'a'.repeat(2000)}\nkeep: true\n`
  await compare(page, left, `value: ${'b'.repeat(2000)}\nkeep: true\n`)
  const scroll = (side: string) => page.locator(`.text-pane-${side} .cm-scroller`)
  await scroll('left').evaluate(element => { element.scrollLeft = 480 })
  for (const side of ['result', 'right']) await expect.poll(() => scroll(side).evaluate(element => element.scrollLeft)).toBe(480)
  await page.getByRole('checkbox', { name: '锁定滚动' }).uncheck()
  await scroll('left').evaluate(element => { element.scrollLeft = 800 })
  await expect.poll(() => scroll('left').evaluate(element => element.scrollLeft)).toBe(800)
  expect(await scroll('right').evaluate(element => element.scrollLeft)).toBe(480)
  await compare(page, left, 'value: short\nkeep: true\n')
  await scroll('left').evaluate(element => { element.scrollLeft = 600 })
  await expect.poll(() => scroll('result').evaluate(element => element.scrollLeft)).toBe(600)
  expect(await scroll('right').evaluate(element => element.scrollLeft)).toBe(0)
  await page.waitForTimeout(150)
  expect(await scroll('left').evaluate(element => element.scrollLeft)).toBe(600)
})

